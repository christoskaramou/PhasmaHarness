'use strict';
// Proven setups: each task Auto routed in a project with checks leaves one record (its kind of work, the preset it ran
// on, whether its checks passed first time, after a correction, or not at all, and its tokens). When, for one kind of
// work, one preset beats another that also ran it at least three times, Auto prefers it there on low and medium
// difficulty; the next task of that kind it does not pass first time drops the preference. Records live beside the
// lessons as setups.json, with a generated setups.md.
const fs = require('node:fs');
const path = require('node:path');

const RECORDS = 'setups.json';
const PAGE = 'setups.md';
const MAX_RECORDS = 300;
const WINDOW = 20;
const MIN_RUNS = 3;
const EASY = ['low', 'medium'];

function readSetups(root) {
  try {
    const data = JSON.parse(fs.readFileSync(path.join(root, RECORDS), 'utf8'));
    return {
      records: Array.isArray(data.records) ? data.records.filter(record => record?.kind && record.preset) : [],
      preferences: Array.isArray(data.preferences) ? data.preferences.filter(entry => entry?.kind && entry.preset) : [],
      blocked: Array.isArray(data.blocked) ? data.blocked.filter(entry => entry?.kind && entry.preset) : [],
    };
  } catch {
    return { records: [], preferences: [], blocked: [] };
  }
}

function writeAtomic(file, text) {
  fs.writeFileSync(file + '.tmp', text);
  fs.renameSync(file + '.tmp', file);
}

const percent = (part, whole) => `${part} of ${whole}`;

function renderPage(data) {
  const preferred = data.preferences.map(entry => `- **${entry.kind}** work: ${entry.label || entry.preset}, since ${new Date(entry.since).toISOString().slice(0, 10)}. ` +
    entry.evidence.map(stats => `${stats.label || stats.preset}: ${percent(stats.clean, stats.runs)} passed first time`).join('; ') + '.');
  const kinds = [...new Set(data.records.map(record => record.kind))].sort();
  const recent = kinds.map(kind => `- ${kind}: ` + statsFor(data.records, kind).map(stats => `${stats.label || stats.preset} ` +
    `${percent(stats.clean, stats.runs)} first time, ${stats.corrected} corrected, ${stats.failed} failed`).join('; '));
  return `# Proven setups\n\nGenerated by Phasma Harness. For each kind of work, the preset that passed this project's checks first time ` +
    `more often than another one that also ran it at least ${MIN_RUNS} times becomes Auto's choice on low and medium difficulty; a task it ` +
    `does not pass first time drops it. The records live in ${RECORDS} beside this page.\n\n## Auto prefers\n\n${preferred.join('\n') || 'Nothing yet.'}\n\n` +
    `## Recent results (last ${WINDOW} low and medium tasks per kind)\n\n${recent.join('\n') || 'No records yet.'}\n`;
}

// Every change re-reads the file first, since several agents' tasks may settle together.
function updateSetups(root, change) {
  fs.mkdirSync(root, { recursive: true });
  const data = readSetups(root);
  const result = change(data);
  writeAtomic(path.join(root, RECORDS), JSON.stringify(data, null, 2));
  writeAtomic(path.join(root, PAGE), renderPage(data));
  return result;
}

// How a settled task's checks went: first time, after a correction, or still failing. Anything else says nothing.
function taskOutcome(task) {
  const corrected = (task.corrections || 0) > (task.startCorrections || 0);
  if (task.state === 'checks-passed')
    return corrected ? 'corrected' : 'clean';

  const last = (task.attempts || []).at(-1);
  if (task.state === 'needs-you' && (last?.results || []).some(result => result.status === 'failed'))
    return 'failed';

  return null;
}

// Per preset, its recent low and medium tasks of one kind.
function statsFor(records, kind) {
  const recent = records.filter(record => record.kind === kind && EASY.includes(record.difficulty)).slice(-WINDOW);
  const byPreset = new Map();
  for (const record of recent) {
    const stats = byPreset.get(record.preset) || { preset: record.preset, label: record.label, provider: record.provider, runs: 0, clean: 0, corrected: 0, failed: 0, tokens: [] };
    stats.runs++;
    stats[record.outcome]++;
    if (Number.isFinite(record.tokens))
      stats.tokens.push(record.tokens);
    byPreset.set(record.preset, stats);
  }
  return [...byPreset.values()].map(stats => ({ ...stats,
    tokens: stats.tokens.length === stats.runs ? Math.round(stats.tokens.reduce((a, b) => a + b, 0) / stats.runs) : null }));
}

// More first-time passes wins, then fewer failures. Tokens only break a tie within one provider, since providers count
// them differently, and a preset without reported tokens never wins on them. 0 is a tie.
function compare(a, b) {
  const rate = stats => stats.clean / stats.runs;
  if (rate(a) !== rate(b))
    return rate(b) - rate(a);
  if (a.failed / a.runs !== b.failed / b.runs)
    return a.failed / a.runs - b.failed / b.runs;
  if (a.provider === b.provider && a.tokens !== null && b.tokens !== null)
    return a.tokens - b.tokens;
  return 0;
}

// The preset that beat another for this kind of work, both with enough runs; null when nothing was compared, it is a
// tie, or the user undid it before.
function provenFor(data, kind) {
  const candidates = statsFor(data.records, kind).filter(stats => stats.runs >= MIN_RUNS).sort(compare);
  if (candidates.length < 2 || compare(candidates[0], candidates[1]) >= 0 || candidates[0].clean < MIN_RUNS)
    return null;
  if (data.blocked.some(entry => entry.kind === kind && entry.preset === candidates[0].preset))
    return null;

  return { kind, preset: candidates[0].preset, label: candidates[0].label, since: Date.now(), evidence: candidates };
}

// Records one task. Returns { rolledBack } when the preferred preset did not pass a task of its kind first time, or
// { proven } when a preference is newly earned; a kind with a preference is not re-derived until it is dropped.
function recordSetup(root, record) {
  return updateSetups(root, data => {
    data.records = [...data.records, record].slice(-MAX_RECORDS);
    const preference = data.preferences.find(entry => entry.kind === record.kind);
    if (preference) {
      const loss = preference.preset === record.preset && EASY.includes(record.difficulty) && record.outcome !== 'clean';
      if (!loss)
        return {};

      data.preferences = data.preferences.filter(entry => entry !== preference);
      return { rolledBack: preference };
    }

    const proven = provenFor(data, record.kind);
    if (proven)
      data.preferences.push(proven);
    return proven ? { proven } : {};
  });
}

// Undo: the preference goes, and that preset is never proposed again for that kind.
function dropPreference(root, kind, preset) {
  return updateSetups(root, data => {
    data.preferences = data.preferences.filter(entry => !(entry.kind === kind && entry.preset === preset));
    if (!data.blocked.some(entry => entry.kind === kind && entry.preset === preset))
      data.blocked.push({ kind, preset, at: Date.now() });
  });
}

module.exports = { RECORDS, PAGE, MIN_RUNS, WINDOW, readSetups, taskOutcome, statsFor, provenFor, recordSetup, dropPreference };
