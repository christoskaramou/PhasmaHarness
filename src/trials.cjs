'use strict';
// Trial rules: a rule Harness found itself (a reflection on a failed run, or a suggested comparison that helped) rides
// the first message of matching tasks that run its check. Three such tasks passing that check on their first attempt
// keep it in the project's PhasmaHarness.md; the failure it targets coming back drops it, or rolls it back once kept. The
// records live beside the lessons as rules.json, with a generated rules.md.
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { failureLine, shape, words } = require('./lessons.cjs');

const RECORDS = 'rules.json';
const PAGE = 'rules.md';
const KEEP_AFTER = 3;
const MAX_TRIALS = 5;
// At most 10 kept rules are always on in PhasmaHarness.md. Past that, the one tasks matched least recently moves out and
// rides only the tasks it matches ("on demand"), like a trial; at most 30 do.
const MAX_KEPT = 10;
const MAX_ON_DEMAND = 30;
const MAX_CARRIED = 3;
const MAX_ON_DEMAND_CARRIED = 2;
const MAX_CHAT_CARRIED = 1;
const BLOCK_LIMIT = 800;
const HEADING = '## Rules Harness learned';
const TRIAL_HEADER = 'Project rules on trial (learned from earlier failures here; follow them unless they conflict with the request):';
const KEPT_HEADER = 'Project rules learned from earlier failures here (follow them unless they conflict with the request):';

function readRules(root) {
  try {
    const records = JSON.parse(fs.readFileSync(path.join(root, RECORDS), 'utf8'));
    return Array.isArray(records) ? records.filter(record => record?.id && record.rule) : [];
  } catch {
    return [];
  }
}

function writeAtomic(file, text) {
  fs.writeFileSync(file + '.tmp', text);
  fs.renameSync(file + '.tmp', file);
}

// A hand-edited rules.json may lack a date; the page still renders.
const date = at => (Number.isFinite(at) ? new Date(at).toISOString().slice(0, 10) : 'an unknown date');

function renderPage(records) {
  const states = { trial: 'On trial', kept: 'Kept', dropped: 'Dropped', removed: 'Removed', 'rolled back': 'Rolled back' };
  const entries = records.map(record => {
    const clean = record.carried.filter(entry => entry.outcome === 'clean').length;
    const where = record.onDemand ? 'for the tasks it matches (not in PhasmaHarness.md)' : 'in PhasmaHarness.md';
    const kept = `Kept ${date(record.keptAt)} ${where}.${record.pinned ? ' Put back by you, so never rolled back automatically.' : ''}`;
    const detail = record.state === 'trial' ? `${clean} of ${KEEP_AFTER} clean tasks so far.`
      : record.state === 'kept' ? kept : `${states[record.state]} ${date(record.endedAt || record.since)}: ${record.reason || ''}`;
    const targets = record.check ? `Targets \`${record.check}\`: ${record.error}` : `Targets a mistake from the chat: ${record.error}`;
    return `- **${states[record.state]}** · ${record.rule}\n  - ${targets}. From ${record.source}, since ${date(record.since)}. ${detail}`;
  });
  return `# Rules on trial\n\nGenerated by Phasma Harness. A rule Harness found rides matching tasks that run its check; ${KEEP_AFTER} of them passing that ` +
    `check first time keep it in PhasmaHarness.md (at most ${MAX_KEPT} there; the rest ride the tasks they match), and the failure it targets coming back ` +
    `drops it, or rolls it back once kept. The records live in ${RECORDS} beside this page.\n\n${entries.join('\n')}\n`;
}

// Every change re-reads the file first, since tasks settling together may each write it.
function updateRules(root, change) {
  fs.mkdirSync(root, { recursive: true });
  const records = readRules(root);
  const result = change(records);
  writeAtomic(path.join(root, RECORDS), JSON.stringify(records, null, 2));
  writeAtomic(path.join(root, PAGE), renderPage(records));
  return result;
}

// Text the user removed, or that a trial dropped or a rollback took out, never comes back; one that only made room may.
function retired(records, rule) {
  const same = records.filter(record => record.rule === rule);
  return !same.some(record => ['trial', 'kept'].includes(record.state)) && same.some(record => !record.room);
}

// The rule tasks matched least recently (ties: kept first), for making room.
function leastMatched(records) {
  const matched = record => record.lastMatchedAt || record.keptAt || 0;
  return [...records].sort((a, b) => matched(a) - matched(b) || (a.keptAt || 0) - (b.keptAt || 0))[0];
}

// Past MAX_ON_DEMAND, the unpinned on-demand rule matched least recently makes room (`except`: the one just added).
function makeRoomOnDemand(records, except) {
  const onDemand = records.filter(record => record.state === 'kept' && record.onDemand);
  if (onDemand.length <= MAX_ON_DEMAND)
    return;

  const old = leastMatched(onDemand.filter(record => !record.pinned && record.id !== except));
  if (old)
    Object.assign(old, { state: 'dropped', endedAt: Date.now(), reason: 'too many rules kept for matching tasks; the least used made room', room: true });
}

// A rule goes on trial once (null when retired); past the cap the oldest trial makes room.
function startTrial(root, { rule, lessonKey, check, error, goal, source }) {
  return updateRules(root, records => {
    const live = records.find(record => record.rule === rule && ['trial', 'kept'].includes(record.state));
    if (live)
      return live;

    if (retired(records, rule))
      return null;

    const trials = records.filter(record => record.state === 'trial').sort((a, b) => a.since - b.since);
    for (const old of trials.slice(0, Math.max(0, trials.length - MAX_TRIALS + 1)))
      Object.assign(old, { state: 'dropped', endedAt: Date.now(), reason: 'too many rules on trial; the oldest made room', room: true });

    const record = { id: randomUUID(), rule, lessonKey, check, error, goal, source, state: 'trial', since: Date.now(), carried: [] };
    records.push(record);
    return record;
  });
}

// A rule is about a request when they share words (the rule's goal and the failure it targets).
const matches = (record, request) => [...words(`${record.goal} ${record.error}`)].some(word => request.has(word));

// A rule from the chat has no check to narrow it, so it needs two words in common with the request it came from.
const chatMatches = (record, request) => [...words(record.goal)].filter(word => request.has(word)).length >= 2;

// A checked rule is about a task that runs its check and shares words with it; a chat rule needs the closer match.
const relevant = (record, request, checkNames) => (record.check ? checkNames.includes(record.check) && matches(record, request) : chatMatches(record, request));

// Trial rules a new task carries: on trial and relevant to it, at most one of them from the chat.
function matchingTrials(records, text, checkNames) {
  const request = words(text);
  let chat = 0;
  return records.filter(record => record.state === 'trial' && relevant(record, request, checkNames))
    .filter(record => record.check || chat++ < MAX_CHAT_CARRIED)
    .slice(0, MAX_CARRIED);
}

// Kept rules out of PhasmaHarness.md ride the tasks they match the same way, fewer at a time, so trials keep their slots.
function matchingOnDemand(records, text, checkNames) {
  const request = words(text);
  return records.filter(record => record.state === 'kept' && record.onDemand && relevant(record, request, checkNames))
    .slice(0, MAX_ON_DEMAND_CARRIED);
}

// Kept rules reach a worker only through the PhasmaHarness.md its turn reads, so a task carries one only when its line
// is there and the task runs its check, or, for a chat rule, matches it closely.
function carriedKept(records, body, checkNames, text = '') {
  const request = words(text);
  return records.filter(record => record.state === 'kept' && record.line && body.includes(record.line) &&
    (record.check ? checkNames.includes(record.check) : chatMatches(record, request)));
}

// A kept line the user deleted from PhasmaHarness.md by hand stays deleted: its rule is marked removed, so it frees its
// place under the cap and its text never comes back.
function forgetDeletedKept(root, body) {
  const deleted = record => record.state === 'kept' && record.line && !body.includes(record.line);
  const records = readRules(root);
  if (!records.some(deleted))
    return records;

  return updateRules(root, current => {
    for (const record of current.filter(deleted))
      Object.assign(record, { state: 'removed', endedAt: Date.now(), reason: 'deleted from PhasmaHarness.md by hand' });

    return current;
  });
}

function trialBlock(records, header = TRIAL_HEADER) {
  let block = header;
  const kept = [];
  for (const record of records) {
    if (block.length + record.rule.length + 3 > BLOCK_LIMIT)
      break;
    block += `\n- ${record.rule}`;
    kept.push(record);
  }
  return { block: kept.length ? block : null, records: kept };
}

const keptBlock = records => trialBlock(records, KEPT_HEADER);

// What one carried task says about a rule: "hit" when any attempt failed its check with the line it targets, "clean"
// when the check ran on the first attempt and passed, otherwise "none" (skipped, not run, or failed another way).
function trialOutcome(task, record) {
  const failed = (task.attempts || []).some(attempt => (attempt.results || []).some(result =>
    result.name === record.check && result.status === 'failed' && shape(failureLine(result)) === shape(record.error)));
  if (failed)
    return 'hit';

  const first = (task.attempts || [])[0]?.results?.find(result => result.name === record.check);
  return !task.checksSkippedByRouter && first?.status === 'passed' ? 'clean' : 'none';
}

// A winning trial is kept: in PhasmaHarness.md while it has room, else in place of the unpinned always-on rule matched
// least recently (`displaces`; the controller moves that one out), else, with all ten pinned, on demand.
function keep(records, record, displaced) {
  Object.assign(record, { state: 'kept', keptAt: Date.now() });
  const alwaysOn = records.filter(entry => entry.state === 'kept' && !entry.onDemand && entry !== record && !displaced.has(entry.id));
  if (alwaysOn.length < MAX_KEPT)
    return record;

  const out = leastMatched(alwaysOn.filter(entry => entry.line && !entry.pinned));
  if (out) {
    displaced.add(out.id);
    return { ...record, displaces: out.id };
  }

  record.onDemand = true;
  makeRoomOnDemand(records, record.id);
  return record;
}

const targets = record => (record.check ? 'the failure it targets' : 'the mistake it targets');

// One carried task's outcome for a trial rule: a hit drops it, the third clean keeps it; null while undecided.
function decideTrial(records, record, task, outcome, displaced) {
  record.carried.push({ taskId: task.id, at: Date.now(), outcome });
  if (outcome === 'hit') {
    Object.assign(record, { state: 'dropped', endedAt: Date.now(), reason: `${targets(record)} came back` });
    return record;
  }

  if (record.carried.filter(entry => entry.outcome === 'clean').length >= KEEP_AFTER)
    return keep(records, record, displaced);

  return null;
}

function rollBack(record, task) {
  return Object.assign(record, { state: 'rolled back', endedAt: Date.now(), reason: `${targets(record)} came back after it was kept`, hitTask: task.id });
}

// Records a settled task's outcome for each checked trial rule it carried and returns the rules that were kept, dropped
// or rolled back. A kept rule it carried rolls back on a hit, unless the user put it back before (pinned). Chat rules
// have no check, so the chat scanner decides them later (recordChatVerdicts).
function recordOutcomes(root, task) {
  return updateRules(root, records => {
    const decided = [];
    const displaced = new Set();
    for (const record of records.filter(entry => entry.state === 'trial' && entry.check && (task.trialRuleIds || []).includes(entry.id))) {
      if (record.carried.some(entry => entry.taskId === task.id))
        continue;

      const result = decideTrial(records, record, task, trialOutcome(task, record), displaced);
      if (result)
        decided.push(result);
    }

    // After the keeps, so the rule moved out is chosen before this task counts as matching any.
    const request = words(task.goal || '');
    for (const record of records.filter(entry => entry.state === 'kept' && (task.keptRuleIds || []).includes(entry.id))) {
      if (record.check ? matches(record, request) : chatMatches(record, request))
        record.lastMatchedAt = Date.now();

      if (record.pinned || !record.check || trialOutcome(task, record) !== 'hit')
        continue;

      decided.push(rollBack(record, task));
    }
    return decided;
  });
}

// The chat scanner's verdicts on the chat rules a task carried: recurred is a hit, avoided is clean, not relevant counts
// for nothing. Once per task and rule, like checked trials.
function recordChatVerdicts(root, task, verdicts) {
  const carried = [...(task.trialRuleIds || []), ...(task.keptRuleIds || [])];
  return updateRules(root, records => {
    const decided = [];
    const displaced = new Set();
    for (const { id, verdict } of verdicts) {
      const record = records.find(entry => entry.id === id && !entry.check && carried.includes(id));
      if (!record || record.carried.some(entry => entry.taskId === task.id))
        continue;

      const outcome = verdict === 'recurred' ? 'hit' : verdict === 'avoided' ? 'clean' : 'none';
      if (record.state === 'trial') {
        const result = decideTrial(records, record, task, outcome, displaced);
        if (result)
          decided.push(result);
      } else if (record.state === 'kept') {
        record.carried.push({ taskId: task.id, at: Date.now(), outcome });
        if (outcome === 'hit' && !record.pinned)
          decided.push(rollBack(record, task));
      }
    }
    return decided;
  });
}

// A kept rule joins the project entry under one heading, as one dated line.
function keepInInstructions(file, record) {
  const body = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  const line = `- ${record.rule} (kept ${date(record.keptAt)})`;
  if (body.includes(`- ${record.rule}`))
    return line;

  let next;
  const at = body.indexOf(HEADING);
  if (at < 0) {
    next = `${body.trimEnd()}\n\n${HEADING}\n\n${line}\n`;
  } else {
    const end = body.indexOf('\n## ', at + HEADING.length);
    next = end < 0 ? `${body.trimEnd()}\n${line}\n` : `${body.slice(0, end).trimEnd()}\n${line}\n${body.slice(end)}`;
  }
  if (Buffer.byteLength(next) > 64 * 1024)
    throw new Error('Keeping this rule would push PhasmaHarness.md past 64 KiB.');

  fs.writeFileSync(file, next);
  return line;
}

// Undo of a kept rule: its line goes, and the heading too once nothing is left under it.
function removeKeptLine(body, line) {
  let next = body.replace(`${line}\n`, '').replace(line, '');
  const at = next.indexOf(HEADING);
  if (at >= 0) {
    const end = next.indexOf('\n## ', at + HEADING.length);
    if (!next.slice(at + HEADING.length, end < 0 ? next.length : end).trim())
      next = `${next.slice(0, at).trimEnd()}\n${end < 0 ? '' : next.slice(end)}`;
  }
  return next;
}

module.exports = { RECORDS, PAGE, KEEP_AFTER, MAX_TRIALS, MAX_KEPT, MAX_ON_DEMAND, HEADING, removeKeptLine, readRules, updateRules, retired, startTrial,
  matchingTrials, matchingOnDemand, trialBlock, keptBlock, makeRoomOnDemand, carriedKept, forgetDeletedKept, trialOutcome, recordOutcomes, recordChatVerdicts,
  keepInInstructions };
