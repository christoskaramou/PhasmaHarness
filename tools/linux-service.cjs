const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFile } = require('node:child_process');
const { promisify } = require('node:util');
const { randomUUID } = require('node:crypto');
const { options, privateData } = require('../src/server.cjs');
const { RemoteSettings } = require('../src/remote-settings.cjs');
const { serviceUnit } = require('../src/runner-linux.cjs');
const OWNER = '# Generated by Phasma Harness\n';

function quote(value) {
  if (typeof value !== 'string' || /[\x00-\x1f\x7f]/.test(value)) throw new Error('Use ordinary paths without control characters.');
  return '"' + value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%') + '"';
}

function renderService({ data, port, origin, node = fs.realpathSync(process.execPath), root = path.resolve(__dirname, '..') }) {
  const configuration = new RemoteSettings(data);
  const value = configuration.validate({ ...configuration.value, enabled: true,
    port: port ?? configuration.value.port, origin: origin === undefined ? configuration.value.origin : origin });
  const args = [node, path.join(root, 'src', 'server.cjs'), '--data', fs.realpathSync(data), '--port', String(value.port)];
  if (value.origin) args.push('--origin', value.origin);
  return OWNER + '[Unit]\nDescription=Phasma Harness runner\nAfter=network.target\n\n' +
    '[Service]\nType=exec\nExitType=main\nRestart=on-failure\nRestartSec=5s\nTimeoutStopSec=20s\n' +
    'KillMode=control-group\nSendSIGKILL=yes\nNoNewPrivileges=yes\nProtectControlGroups=yes\nDelegate=no\nUMask=0077\n' +
    'UnsetEnvironment=NODE_OPTIONS NODE_PATH ELECTRON_RUN_AS_NODE\n' +
    'ExecStart=:' + args.map(quote).join(' ') + '\n\n' +
    '[Install]\nWantedBy=default.target\n';
}

async function install(args) {
  if (process.platform !== 'linux' || process.getuid() === 0) throw new Error('Install the service as its regular Linux user.');
  if (Number(process.versions.node.split('.')[0]) < 24) throw new Error('Use Node.js 24 or newer.');
  const settings = options(args);
  if (settings.link) throw new Error('Use src/server.cjs --connection-link to print the private connection link.');
  const data = privateData(settings.data), unit = serviceUnit(data), body = renderService({ ...settings, data });
  const run = promisify(execFile);
  const status = await run('/usr/bin/systemctl', ['--user', 'show', unit, '--property=ActiveState', '--value'], { timeout: 5000, maxBuffer: 16384 });
  if (!['inactive', 'failed'].includes(status.stdout.trim()))
    throw new Error('Stop ' + unit + ' on the runner host before reinstalling its service.');
  const directory = path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'systemd', 'user');
  fs.mkdirSync(directory, { recursive: true, mode: 0o700 });
  const filename = path.join(directory, unit);
  const stat = fs.lstatSync(filename, { throwIfNoEntry: false });
  if (stat) {
    if (!stat.isFile() || stat.isSymbolicLink() || stat.nlink !== 1 || stat.uid !== process.getuid() ||
        !fs.readFileSync(filename, 'utf8').startsWith(OWNER)) throw new Error('An unrecognized service file already exists. Review it before replacing it.');
  }
  const temporary = path.join(data, 'service-check-' + randomUUID());
  fs.mkdirSync(temporary, { mode: 0o700 });
  const candidate = path.join(temporary, unit);
  try {
    fs.writeFileSync(candidate, body, { flag: 'wx', mode: 0o600 });
    await run('/usr/bin/systemd-analyze', ['--user', 'verify', candidate], { timeout: 10000, maxBuffer: 16384 });
    try { await run('/usr/bin/loginctl', ['--no-ask-password', 'enable-linger', String(process.getuid())], { timeout: 10000, maxBuffer: 16384 }); }
    catch { throw new Error('Startup after logout or reboot needs user lingering. Run loginctl enable-linger in an authorized terminal, then rerun setup.'); }
    const staged = filename + '.' + randomUUID() + '.tmp';
    try { fs.writeFileSync(staged, body, { flag: 'wx', mode: 0o600 }); fs.renameSync(staged, filename); }
    finally { try { fs.unlinkSync(staged); } catch (error) { if (error.code !== 'ENOENT') throw error; } }
    await run('/usr/bin/systemctl', ['--user', 'daemon-reload'], { timeout: 10000, maxBuffer: 16384 });
    await run('/usr/bin/systemctl', ['--user', 'enable', unit], { timeout: 10000, maxBuffer: 16384 });
    await run('/usr/bin/systemctl', ['--user', 'restart', unit], { timeout: 30000, maxBuffer: 16384 });
    console.log('Installed and enabled ' + unit);
    const command = [process.execPath, path.resolve(__dirname, '../src/server.cjs'), '--data', data, '--connection-link']
      .map(value => "'" + value.replace(/'/g, "'\\''") + "'").join(' ');
    console.log('Print your private connection link with: ' + command);
  } finally { fs.rmSync(candidate, { force: true }); fs.rmdirSync(temporary); }
}

if (require.main === module) install(process.argv.slice(2)).catch(error => { console.error(error.message); process.exitCode = 1; });
module.exports = { renderService, quote, install };
